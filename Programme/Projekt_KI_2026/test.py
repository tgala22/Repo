while True:
  # Das Programm pausiert hier und wartet auf deine Eingabe + Enter
  eingabe = input(
      "Gib einen Buchstaben ein (oder 'q' + Enter zum Beenden): "
  )

  # .strip().lower() entfernt Leerzeichen und ignoriert Groß-/Kleinschreibung
  if eingabe.strip().lower() == 'q':
    print("Programm wird beendet. Tschüss!")
    break  # Bricht die while-Schleife ab

  print(f"Du hast '{eingabe}' eingegeben. Weiter geht's...\n")
